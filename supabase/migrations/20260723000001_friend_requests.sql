-- Friend requests: send → accept / reject, replacing the old instant-befriend redeem flow.
-- Written idempotently; apply via the dashboard SQL Editor.
--
-- Model: a request is ONE row (requester → addressee, status pending). Accepting it creates the
-- friendship BOTH ways (exactly like the old redeem_friend_code did) and marks the request accepted.
-- All mutations go through the SECURITY DEFINER RPCs below — clients get read-only SELECT on their
-- own requests and cannot write the table directly. redeem_friend_code() is left in place for
-- backward compatibility but the app now uses send_friend_request() instead.

-- ── friend_requests ────────────────────────────────────────────────────────────
create table if not exists public.friend_requests (
  id bigint generated by default as identity primary key,
  requester uuid not null references auth.users (id) on delete cascade,
  addressee uuid not null references auth.users (id) on delete cascade,
  status text not null default 'pending'
    check (status in ('pending', 'accepted', 'rejected', 'cancelled')),
  created_at timestamptz not null default now(),
  responded_at timestamptz,
  check (requester <> addressee)
);
-- At most one PENDING request per direction; a new one is allowed once a prior one resolves.
create unique index if not exists uq_friend_requests_pending
  on public.friend_requests (requester, addressee) where status = 'pending';
create index if not exists idx_friend_requests_addressee on public.friend_requests (addressee, status);
create index if not exists idx_friend_requests_requester on public.friend_requests (requester, status);

alter table public.friend_requests enable row level security;

-- Read: either side of a request may see it. No client insert/update/delete — the RPCs own writes.
drop policy if exists "friend_requests_select" on public.friend_requests;
create policy "friend_requests_select" on public.friend_requests
  for select using (requester = auth.uid() or addressee = auth.uid());

-- ── RPCs ──────────────────────────────────────────────────────────────────────

-- Accept a request addressed to me: creates the friendship both ways, marks it accepted.
create or replace function public.accept_friend_request(request_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare r public.friend_requests;
begin
  select * into r from public.friend_requests where id = request_id;
  if not found then raise exception 'request not found'; end if;
  if r.addressee <> auth.uid() then raise exception 'not your request to accept'; end if;
  if r.status <> 'pending' then raise exception 'request is not pending'; end if;
  insert into public.friends (user_id, friend_id) values (r.requester, r.addressee) on conflict do nothing;
  insert into public.friends (user_id, friend_id) values (r.addressee, r.requester) on conflict do nothing;
  update public.friend_requests set status = 'accepted', responded_at = now() where id = request_id;
end;
$$;

-- Reject a request addressed to me.
create or replace function public.reject_friend_request(request_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare r public.friend_requests;
begin
  select * into r from public.friend_requests where id = request_id;
  if not found then raise exception 'request not found'; end if;
  if r.addressee <> auth.uid() then raise exception 'not your request'; end if;
  if r.status <> 'pending' then raise exception 'request is not pending'; end if;
  update public.friend_requests set status = 'rejected', responded_at = now() where id = request_id;
end;
$$;

-- Cancel a request I sent (requester withdraws).
create or replace function public.cancel_friend_request(request_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare r public.friend_requests;
begin
  select * into r from public.friend_requests where id = request_id;
  if not found then raise exception 'request not found'; end if;
  if r.requester <> auth.uid() then raise exception 'not your request'; end if;
  if r.status <> 'pending' then raise exception 'request is not pending'; end if;
  update public.friend_requests set status = 'cancelled', responded_at = now() where id = request_id;
end;
$$;

-- Send a friend request by the other person's friend code. Security definer so it can resolve the
-- code → target and insert the addressee side. Handles the edge cases: own code, already friends,
-- a duplicate pending request, and the "they already asked me" case (auto-accepts theirs instead).
-- Returns the new request id, or null when it auto-accepted / no-oped.
create or replace function public.send_friend_request(code text)
returns bigint language plpgsql security definer set search_path = public as $$
declare target uuid; existing bigint; req_id bigint;
begin
  select id into target from public.profiles where upper(friend_code) = upper(trim(code));
  if target is null then raise exception 'unknown friend code'; end if;
  if target = auth.uid() then raise exception 'that is your own code'; end if;

  if exists (select 1 from public.friends f where f.user_id = auth.uid() and f.friend_id = target) then
    raise exception 'already friends';
  end if;

  -- They already sent ME a pending request → accept it rather than create a crossing duplicate.
  select id into existing from public.friend_requests
    where requester = target and addressee = auth.uid() and status = 'pending' limit 1;
  if existing is not null then
    perform public.accept_friend_request(existing);
    return null;
  end if;

  insert into public.friend_requests (requester, addressee) values (auth.uid(), target)
    on conflict (requester, addressee) where status = 'pending' do nothing
    returning id into req_id;
  return req_id;  -- null if a pending request already existed
end;
$$;

-- Incoming pending requests addressed to me, with the requester's username (their profile isn't
-- readable yet — we aren't friends — so this security-definer view exposes only id + username).
create or replace function public.incoming_friend_requests()
returns table (id bigint, requester uuid, username text, created_at timestamptz)
language sql security definer set search_path = public as $$
  select r.id, r.requester, p.username, r.created_at
  from public.friend_requests r
  join public.profiles p on p.id = r.requester
  where r.addressee = auth.uid() and r.status = 'pending'
  order by r.created_at desc;
$$;

-- Outgoing pending requests I've sent, with the addressee's username.
create or replace function public.outgoing_friend_requests()
returns table (id bigint, addressee uuid, username text, created_at timestamptz)
language sql security definer set search_path = public as $$
  select r.id, r.addressee, p.username, r.created_at
  from public.friend_requests r
  join public.profiles p on p.id = r.addressee
  where r.requester = auth.uid() and r.status = 'pending'
  order by r.created_at desc;
$$;
